#!/usr/bin/env python3
"""Map each workflow job's Python version file to the constraints file it installs.

Workflows never pin a Python literal: every ``actions/setup-python`` step reads one of
the version files in ``VERSION_FILES``. A *lane* is one (version file, constraints file)
pairing that some job actually uses. ``python-compat.yml`` dry-run resolves every lane
on its own Python, so a dependency or Python bump that cannot install on a lane fails
before it merges.

Usage:
  python scripts/python_lanes.py           # print lanes as a GitHub Actions matrix (JSON)
  python scripts/python_lanes.py --check   # exit non-zero on any policy violation
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

try:  # imported as scripts.python_lanes (tests) or run as scripts/python_lanes.py
    from scripts.lane_inputs import LANES
except ModuleNotFoundError:
    from lane_inputs import LANES

ROOT = Path(__file__).resolve().parent.parent
WORKFLOWS = ROOT / ".github" / "workflows"
CONSTRAINTS = ROOT / "constraints"

DEFAULT_VERSION_FILE = ".python-version"
# The ASR stack (whisperX pins torch~=2.8.0, which has no cp314 wheels) lags the fleet.
ASR_VERSION_FILE = ".github/python/asr/.python-version"
VERSION_FILES = (DEFAULT_VERSION_FILE, ASR_VERSION_FILE)
MATRIX_VERSION_FILE = "${{ matrix.version_file }}"

CONSTRAINTS_RE = re.compile(r"constraints/([\w-]+)\.txt")
HEADER_PYTHON_RE = re.compile(r"autogenerated by pip-compile with Python (\d+\.\d+)")


def read_version(version_file: str) -> str:
    return (ROOT / version_file).read_text().strip()


def _setup_python_steps(job: dict) -> list[dict]:
    return [s for s in job.get("steps") or [] if "actions/setup-python@" in (s.get("uses") or "")]


def lanes() -> tuple[list[dict], list[str]]:
    """Return (lanes, problems) found across every workflow job."""
    found: dict[tuple[str, str], set[str]] = {}
    problems: list[str] = []
    for wf in sorted(WORKFLOWS.glob("*.yml")):
        jobs = (yaml.safe_load(wf.read_text()) or {}).get("jobs") or {}
        for job_name, job in jobs.items():
            where = f"{wf.name}:{job_name}"
            version_files = set()
            for step in _setup_python_steps(job):
                with_ = step.get("with") or {}
                if "python-version" in with_:
                    problems.append(f"{where}: setup-python pins a literal python-version")
                vf = with_.get("python-version-file")
                if vf == MATRIX_VERSION_FILE:
                    continue  # python-compat.yml's resolve job, fed from this script's own output
                if vf not in VERSION_FILES:
                    problems.append(
                        f"{where}: python-version-file must be one of {VERSION_FILES}, got {vf!r}"
                    )
                    continue
                version_files.add(vf)
            if len(version_files) > 1:
                problems.append(f"{where}: mixes Python version files {sorted(version_files)}")
            constraint_files = set(CONSTRAINTS_RE.findall(yaml.safe_dump(job)))
            for name in sorted(constraint_files - LANES.keys()):
                problems.append(f"{where}: constraints/{name}.txt is not a lane in lane_inputs.py")
            constraint_files &= LANES.keys()
            if "asr" in constraint_files and version_files != {ASR_VERSION_FILE}:
                problems.append(f"{where}: installs constraints/asr.txt without {ASR_VERSION_FILE}")
            for vf in version_files:
                for name in constraint_files:
                    found.setdefault((vf, name), set()).add(where)
    result = [
        {
            "version_file": vf,
            "python": read_version(vf),
            "constraints": f"constraints/{name}.txt",
            "extras": ",".join(LANES[name]),
            "jobs": len(jobs_),
        }
        for (vf, name), jobs_ in sorted(found.items())
    ]
    return result, problems


def check_asr_python_pins() -> list[str]:
    """Python versions set outside setup-python must agree with the ASR version file.

    The constraints are compiled for, and the Modal/Beam/audio-runner images run, the
    ASR Python, and Renovate filters lock updates by it. None of these can read a
    .python-version file, so they are checked here.
    """
    asr = read_version(ASR_VERSION_FILE)
    sources = {
        "scripts/compile_constraints.sh": rf"python:{re.escape(asr)}-slim",
        "scripts/compute/modal_app.py": rf'add_python="{re.escape(asr)}"',
        "scripts/compute/modal_canary.py": rf'add_python="{re.escape(asr)}"',
        "scripts/compute/beam_app.py": rf'python_version="python{re.escape(asr)}"',
        ".github/audio-runner/Dockerfile": rf"\bpython{re.escape(asr)}\b",
        ".github/renovate.json5": rf'python: "{re.escape(asr)}"',
    }
    problems = [
        f"{path}: expected the ASR Python {asr} (pattern {pattern!r})"
        for path, pattern in sources.items()
        if not re.search(pattern, (ROOT / path).read_text())
    ]
    for txt in sorted(CONSTRAINTS.glob("*.txt")):
        m = HEADER_PYTHON_RE.search(txt.read_text())
        if m and m.group(1) != asr:
            problems.append(
                f"constraints/{txt.name}: compiled with Python {m.group(1)}, ASR lane is {asr}"
            )
    return problems


def main(argv: list[str]) -> int:
    found, problems = lanes()
    problems += check_asr_python_pins()
    if "--check" in argv:
        for p in problems:
            print(f"::error::{p}")
        return 1 if problems else 0
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    print(json.dumps({"include": found}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
