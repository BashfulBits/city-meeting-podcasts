#!/usr/bin/env python3
"""Write one pip-compile input per constraints lane, generated from pyproject.toml.

pyproject.toml stays the only place dependencies are declared. Each lane's
``constraints/<lane>.in`` lists the base dependencies plus that lane's extras, and
``scripts/compile_constraints.sh`` compiles ``<lane>.in`` -> ``<lane>.txt``.

Why not compile straight from pyproject.toml with ``--extra``: Renovate's pip-compile
manager keys a project by its source file, so four locks sharing pyproject.toml become
one project whose current versions are read from the alphabetically first lock (asr.txt).
Packages absent from that lock (the LLM stack) then never get an update. A separate
source per lane gives Renovate one project per lock.

Usage:
  python scripts/lane_inputs.py           # (re)write constraints/*.in
  python scripts/lane_inputs.py --check   # exit non-zero if any .in is stale

Standard library only: it runs inside the pinned compile container before pip-compile.
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONSTRAINTS = ROOT / "constraints"

# Lane -> pyproject extras. Keep in sync with constraints/README.md.
LANES: dict[str, tuple[str, ...]] = {
    # `wer` (H15 L3 calibration report) folds into prod.txt rather than asr.txt: it's just
    # jiwer, deliberately kept out of the faster-whisper/WhisperX/torch stack asr.txt resolves.
    "prod": ("storage", "wer", "llm"),
    # `asr-align2` (H15 L2, torchcodec) folds into the same asr.txt resolution rather than a
    # separate lock: torch/torchaudio are already a transitive pin via WhisperX, and compiling
    # them separately risks two constraint files disagreeing on the same package.
    "asr": ("storage", "asr", "asr-align2"),
    "chapter-research": ("chapter-research",),
    # `wer` also needs to be in dev.txt: ci.yml's `test` job installs against this file, and
    # the H15 L3 tests exercise real jiwer computation.
    "dev": ("storage", "dev", "wer", "llm"),
}


def render(lane: str) -> str:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    extras = LANES[lane]
    requirements: list[str] = []
    for req in [*project["dependencies"]] + [
        r for extra in extras for r in project["optional-dependencies"][extra]
    ]:
        if req not in requirements:
            requirements.append(req)
    header = [
        "# Generated by scripts/lane_inputs.py from pyproject.toml -- do not edit.",
        f"# Lane {lane!r}: base dependencies + extras {', '.join(extras)}.",
    ]
    return "\n".join(header + requirements) + "\n"


def main(argv: list[str]) -> int:
    stale = []
    for lane in LANES:
        path = CONSTRAINTS / f"{lane}.in"
        text = render(lane)
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text)
    for path in stale:
        print(f"::error::{path} is stale -- run scripts/lane_inputs.py (pyproject.toml changed)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
