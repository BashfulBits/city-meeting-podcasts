"""Offline, file-based GLiDE batch runner; no cloud transport or callbacks.

Input and output are gzip JSONL. The caller supplies a pinned local model directory;
model revision verification and durable cloud publication belong to a later handoff.
"""

from __future__ import annotations

import argparse
import gzip
import json
import os
import resource
import sys
import tempfile
import time
from collections.abc import Callable
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from citypods.judging.decision_batch import canonical_json, native_request, normalize_results
from citypods.judging.decision_profile import FallbackWatch, InferenceProfile

MAX_COMPRESSED_BYTES = 16 * 1024 * 1024
MAX_EXPANDED_BYTES = 64 * 1024 * 1024
MAX_ROWS = 1000
# Opt-in diagnostic: re-run the first N forward micro-batches on identical inputs and record the
# warm time beside the cold one. Costs up to N extra forwards, so size the task timeout for it.
WARM_REPEATS_ENV = "CITYPODS_DECISION_PROFILE_WARM_REPEATS"
MAX_WARM_REPEATS = 16


def _unique_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON key")
        result[key] = value
    return result


def _read_requests(path: Path) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    if path.stat().st_size > MAX_COMPRESSED_BYTES:
        raise ValueError("compressed input exceeds byte limit")
    with gzip.open(path, "rb") as source:
        data = source.read(MAX_EXPANDED_BYTES + 1)
    if len(data) > MAX_EXPANDED_BYTES:
        raise ValueError("expanded input exceeds byte limit")
    lines = data.splitlines()
    if not lines or len(lines) > MAX_ROWS:
        raise ValueError("input must contain between 1 and 1000 rows")
    rows = [json.loads(line, object_pairs_hook=_unique_object) for line in lines]
    if any(not isinstance(row, dict) for row in rows):
        raise ValueError("each input row must be an object")
    requests = [native_request(row) for row in rows]
    ids = [row["item_id"] for row in rows]
    if len(set(ids)) != len(ids):
        raise ValueError("duplicate item IDs")
    return rows, requests


def _cuda_sync() -> None:
    torch = sys.modules.get("torch")
    if torch is not None and torch.cuda.is_available():
        torch.cuda.synchronize()


def _warm_repeats() -> int:
    value = os.environ.get(WARM_REPEATS_ENV, "0")
    if not value.isdecimal() or int(value) > MAX_WARM_REPEATS:
        raise ValueError(f"{WARM_REPEATS_ENV} must be an integer from 0 through {MAX_WARM_REPEATS}")
    return int(value)


def run_batch(
    input_path: Path,
    output_path: Path,
    load_model: Callable[[], tuple[Any, type[Exception]]],
) -> dict[str, Any]:
    """Run a validated batch and return telemetry; load_model returns model and error type."""
    input_path, output_path = Path(input_path), Path(output_path)
    if input_path.resolve() == output_path.resolve():
        raise ValueError("input and output must be different files")
    started_at = datetime.now(UTC).isoformat()
    started = time.monotonic()
    rows, requests = _read_requests(input_path)
    warm_repeats = _warm_repeats()
    load_started = time.monotonic()
    print("decision batch model load started", flush=True)
    watch = FallbackWatch().install()
    try:
        model, request_error = load_model()
        inference_started = time.monotonic()
        print(f"decision batch model loaded in {inference_started - load_started:.2f}s", flush=True)
        profile = InferenceProfile(model, watch, sync=_cuda_sync, warm_repeats=warm_repeats)
        replies = model.decide_batch(requests)
        inference_finished = time.monotonic()
        watch.assert_fast()
    finally:
        watch.uninstall()
    print(
        f"decision batch inference finished in {inference_finished - inference_started:.2f}s",
        flush=True,
    )
    if not isinstance(replies, (list, tuple)) or len(replies) != len(rows):
        raise ValueError("wrong response cardinality")
    converted = []
    for row, reply in zip(rows, replies, strict=True):
        if isinstance(reply, request_error):
            # This exact error is generated by the pinned runtime after tokenization.
            if str(reply) == "prompt exceeds the maximum context length":
                converted.append({"item_id": row["item_id"], "status": "too_large"})
            else:
                raise ValueError("unclassified native request error") from None
        else:
            converted.append(reply)
    results = normalize_results(rows, converted)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=output_path.parent, delete=False) as raw:
            temporary = Path(raw.name)
            with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as output:
                for result in results:
                    output.write((canonical_json(result) + "\n").encode("utf-8"))
        os.replace(temporary, output_path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    torch = sys.modules.get("torch")
    gpu_peak_bytes = None
    if torch is not None and torch.cuda.is_available():
        torch.cuda.synchronize()
        gpu_peak_bytes = torch.cuda.max_memory_allocated()
    host_peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    host_peak_bytes = host_peak if sys.platform == "darwin" else host_peak * 1024
    input_tokens = [result["input_tokens"] for result in results if "input_tokens" in result]
    return {
        "local_processing_started_at": started_at,
        "input_count": len(rows),
        "valid_count": sum(result["status"] == "ok" for result in results),
        "input_tokens": input_tokens,
        "profile": profile.finish(input_tokens),
        "validation_seconds": load_started - started,
        "load_seconds": inference_started - load_started,
        "inference_seconds": inference_finished - inference_started,
        "total_seconds": time.monotonic() - started,
        "host_peak_bytes": host_peak_bytes,
        "gpu_peak_bytes": gpu_peak_bytes,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--model-dir", type=Path, required=True)
    parser.add_argument("--token-budget", type=int, default=16384)
    parser.add_argument("--max-len", type=int, default=4096)
    args = parser.parse_args()
    if not args.model_dir.is_dir():
        parser.error("--model-dir must be an existing local directory")
    if args.token_budget <= 0 or args.max_len <= 0:
        parser.error("token limits must be positive")

    def load_model() -> tuple[Any, type[Exception]]:
        # Import only after the entire input has passed validation.
        from glide.model import Glide
        from glide.prompt import RequestError

        model = Glide.from_pretrained(
            str(args.model_dir.resolve()),
            vision=False,
            token_budget=args.token_budget,
            max_len=args.max_len,
        )
        return model, RequestError

    run_batch(args.input, args.output, load_model)


if __name__ == "__main__":
    main()
