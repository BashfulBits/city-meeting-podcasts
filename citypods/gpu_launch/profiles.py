"""GPU classes, model profiles and measured calibrations.

Prices are Cloud Run list rates for regular (not delayed) jobs, in microdollars per second, before
any free tier (review/59, "Budget and latency"). Calibrations are data: ``config/gpu_profiles.json``
holds one measured record per (model, GPU) and is regenerated by ``scripts/gpu_calibrate.py`` from
profile telemetry, so adding a model or GPU never edits planner code.
"""

from __future__ import annotations

import json
import math
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

PROFILES_PATH = Path(__file__).resolve().parents[2] / "config" / "gpu_profiles.json"
CPU_RATE = 18.0  # microdollars per vCPU-second
GIB_RATE = 2.0  # microdollars per GiB-second
CONFIDENCE = ("measured", "estimated")
CACHE_MODES = ("none", "configs", "archive")


@dataclass(frozen=True)
class GpuClass:
    """One launchable accelerator envelope (a Cloud Run GPU job)."""

    name: str
    accelerator: str  # Cloud Run nodeSelector accelerator value
    cuda_arch: str
    region: str
    vram_gib: float  # as seen by torch, not the marketing size
    cpu: int
    memory_gib: int
    max_token_budget: (
        int  # padded tokens per forward micro-batch the envelope has been shown to hold
    )
    gpu_rate: float  # microdollars per second

    @property
    def rate(self) -> float:
        """Billed microdollars per second for the whole envelope."""
        return self.gpu_rate + self.cpu * CPU_RATE + self.memory_gib * GIB_RATE


GPU_CLASSES: dict[str, GpuClass] = {
    "L4": GpuClass("L4", "nvidia-l4", "sm_89", "us-east4", 22.0, 4, 16, 16384, 186.7),
    "RTX_PRO_6000": GpuClass(
        "RTX_PRO_6000", "nvidia-rtx-pro-6000", "sm_120", "us-central1", 95.0, 20, 80, 16384, 365.3
    ),
}


@dataclass(frozen=True)
class Calibration:
    """Measured behaviour of one model on one GPU class."""

    load_seconds: float  # median weights-to-ready time from object storage
    load_seconds_p90: float  # tail load time; sizes the timeout and reservation
    startup_seconds: float  # container start, imports and result publication
    tokens_per_second: float  # padded tokens through the forward path, warm kernels
    cold_overhead_seconds: float  # extra forward time with no cache: kernels compile and autotune
    config_overhead_seconds: float  # extra forward time with fla prebaked configs only
    token_budget: int  # padded-token micro-batch size the throughput was measured at
    peak_gpu_gib: float
    confidence: str
    source: str

    def __post_init__(self) -> None:
        if self.confidence not in CONFIDENCE:
            raise ValueError("confidence must be 'measured' or 'estimated'")
        if self.load_seconds_p90 < self.load_seconds:
            raise ValueError("load_seconds_p90 must be at least load_seconds")
        for value in (
            self.load_seconds,
            self.load_seconds_p90,
            self.startup_seconds,
            self.cold_overhead_seconds,
            self.config_overhead_seconds,
        ):
            if not math.isfinite(value) or value < 0:
                raise ValueError("calibration seconds must be finite and non-negative")
        if not math.isfinite(self.tokens_per_second) or self.tokens_per_second <= 0:
            raise ValueError("tokens_per_second must be positive")
        if self.token_budget <= 0 or self.peak_gpu_gib <= 0:
            raise ValueError("token_budget and peak_gpu_gib must be positive")


@dataclass(frozen=True)
class ModelProfile:
    model_id: str
    family: str  # selects the warm-up shape family
    revision: str
    weight_gib: float
    max_len: int
    calibrations: Mapping[str, Calibration]
    notes: str = ""

    def calibration(self, gpu: str) -> Calibration | None:
        return self.calibrations.get(gpu)


def _calibration(raw: Mapping[str, Any]) -> Calibration:
    allowed = set(Calibration.__dataclass_fields__)
    if set(raw) != allowed:
        raise ValueError(f"calibration fields must be exactly {sorted(allowed)}")
    return Calibration(**raw)


def load_profiles(path: Path = PROFILES_PATH) -> dict[str, ModelProfile]:
    """Load and validate model profiles; unknown GPUs or fields fail closed."""
    document = json.loads(Path(path).read_text())
    if document.get("schema_version") != 1:
        raise ValueError("unsupported profile schema version")
    profiles: dict[str, ModelProfile] = {}
    for model_id, raw in document["models"].items():
        if set(raw) != {"family", "revision", "weight_gib", "max_len", "calibrations", "notes"}:
            raise ValueError(f"unexpected profile fields for {model_id}")
        unknown = set(raw["calibrations"]) - set(GPU_CLASSES)
        if unknown:
            raise ValueError(f"unknown GPU classes for {model_id}: {sorted(unknown)}")
        profiles[model_id] = ModelProfile(
            model_id=model_id,
            family=raw["family"],
            revision=raw["revision"],
            weight_gib=float(raw["weight_gib"]),
            max_len=int(raw["max_len"]),
            calibrations={gpu: _calibration(c) for gpu, c in raw["calibrations"].items()},
            notes=raw["notes"],
        )
    return profiles
